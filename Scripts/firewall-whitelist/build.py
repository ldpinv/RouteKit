"""Bundle the shared firewall whitelist logic for each client, without dependencies."""

from argparse import ArgumentParser
from pathlib import Path


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    folder = Path(__file__).resolve().parent
    core = (folder / "core.js").read_bytes().rstrip()
    for client in ("surge", "egern"):
        entry = (folder / f"{client}-entry.js").read_bytes().rstrip()
        output = folder / f"{client}.js"
        bundle = b"// Generated by build.py from core.js and the client entry.\n" + core + b"\n\n" + entry + b"\n"
        if args.check:
            if not output.is_file() or output.read_bytes() != bundle:
                parser.exit(1, f"{output.name} is stale. Run build.py.\n")
        else:
            output.write_bytes(bundle)


if __name__ == "__main__":
    main()
